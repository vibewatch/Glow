interface LocaleContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (value: string) => string;
}

const LocaleContext = createContext<LocaleContextValue>({
  locale: "zh",
  setLocale: () => undefined,
  t: (value) => value,
});

export function LocaleProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("zh");

  useEffect(() => {
    const task = window.setTimeout(() => {
      if (window.localStorage.getItem("glow-locale") === "en") setLocaleState("en");
    }, 0);
    return () => window.clearTimeout(task);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "en" ? "en" : "zh-CN";
    document.title = locale === "en" ? "Glow PRO · Landscape Photography Weather Map" : "霁光 PRO · 风光摄影天气地图";
  }, [locale]);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
    window.localStorage.setItem("glow-locale", next);
  }, []);
  const t = useCallback((value: string) => locale === "en" ? translateGenerated(value) : value, [locale]);
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  return useContext(LocaleContext);
}
